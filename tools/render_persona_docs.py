"""Render persona-templated documents deterministically and check for drift (#733).

Design: docs/persona-template-design.md. Only documents listed in
synthetic/persona-template-manifest.json render; each maps one
docs/templates/*.md.in source to one Markdown output. Values come only from
synthetic/personas.json.

Template syntax, replaced in one left-to-right pass (inserted values are never
re-parsed), identically in prose and inside code fences:
  {persona.KEY.FIELD}  canonical value; KEY must be a persona key and FIELD
                       one of its string fields
  {{  }}               a literal brace
Any other brace (unknown key or field, malformed or unclosed token, a lone
brace) is an error. No format evaluation, expressions, attribute traversal,
includes, shell, network or secret access.

Default mode checks only: every listed document is rendered in memory as
UTF-8 with LF line endings and a single final newline, prefixed by a short
source-template notice, and compared with the exact committed bytes of its
output; any difference, a missing output or a directly edited output is drift.
Check mode never writes. --write updates drifted outputs locally and is
refused in CI (GITHUB_ACTIONS=true or CI=true).

Standard library only. Usage:
  python tools/render_persona_docs.py [--root DIR] [--write]
Exit 0 when every output matches, 1 on drift, 2 on a manifest, persona-data,
template or path error. Messages name paths, line/column positions, keys and
fields only, never persona values.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import stat
import sys
import tempfile
import unicodedata
from pathlib import Path

MANIFEST = "synthetic/persona-template-manifest.json"
PERSONAS = "synthetic/personas.json"
MANIFEST_VERSION = 1
PERSONAS_VERSION = 1
TEMPLATE_DIR = "docs/templates/"
SOURCE_SUFFIX = ".md.in"
OUTPUT_SUFFIX = ".md"
MANIFEST_KEYS = {"version", "documents"}
ENTRY_REQUIRED = {"source", "output"}
ENTRY_OPTIONAL = {"forbidden_fields"}
NAME = r"[a-z][a-z0-9_]*"
SCAN = re.compile(r"\{\{|\}\}|\{persona\.(" + NAME + r")\.(" + NAME + r")\}|[{}]")
NOTICE = ("<!-- Generated by tools/render_persona_docs.py from {source}; "
          "edit the template, not this file. -->\n")


class RenderError(Exception):
    """A manifest, persona-data, template or path error (exit 2)."""


def _reject_duplicates(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            raise RenderError(f"duplicate JSON key: {key}")
        out[key] = value
    return out


def _is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def check_relpath(rel, what):
    """A repository-relative POSIX path: no absolute, empty, dot or hidden parts."""
    if not isinstance(rel, str) or not rel:
        raise RenderError(f"{what}: path must be a non-empty string")
    if "\\" in rel or "\0" in rel or rel.startswith("/") or re.match(r"^[A-Za-z]:", rel):
        raise RenderError(f"{what}: path must be relative POSIX: {rel!r}")
    if any(unicodedata.category(ch) == "Cc" for ch in rel):
        raise RenderError(f"{what}: control character in path: {rel!r}")
    for part in rel.split("/"):
        if part in ("", ".", ".."):
            raise RenderError(f"{what}: empty, '.' or '..' path component: {rel!r}")
        if part.startswith("."):
            raise RenderError(f"{what}: hidden path component: {rel!r}")
    return rel


def contained(root, rel, what):
    """root/rel with no symlink component and resolving inside root.

    Containment is checked before anything under the path is opened.
    """
    path = root
    for part in rel.split("/"):
        path = path / part
        try:
            mode = os.lstat(path).st_mode
        except FileNotFoundError:
            break
        if stat.S_ISLNK(mode):
            raise RenderError(f"{what}: symlink in path: {rel}")
    full = root / rel
    try:
        full.resolve(strict=False).relative_to(root)
    except ValueError:
        raise RenderError(f"{what}: path escapes the repository: {rel}") from None
    return full


def read_regular(root, rel, what):
    full = contained(root, rel, what)
    try:
        mode = os.lstat(full).st_mode
    except FileNotFoundError:
        raise RenderError(f"{what}: missing file: {rel}") from None
    if not stat.S_ISREG(mode):
        raise RenderError(f"{what}: not a regular file: {rel}")
    try:
        return full.read_bytes()
    except OSError as exc:
        raise RenderError(f"{what}: unreadable: {rel} ({exc.strerror})") from None


def decode_text(data, what):
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        raise RenderError(f"{what}: not valid UTF-8") from None
    if text.startswith("\ufeff"):
        raise RenderError(f"{what}: byte-order mark not allowed")
    return text


def load_json(root, rel, what):
    text = decode_text(read_regular(root, rel, what), what)
    try:
        return json.loads(text, object_pairs_hook=_reject_duplicates)
    except json.JSONDecodeError as exc:
        raise RenderError(f"{what}: invalid JSON at line {exc.lineno}") from None


def load_personas(root):
    data = load_json(root, PERSONAS, PERSONAS)
    if not isinstance(data, dict) or not _is_int(data.get("version")):
        raise RenderError(f"{PERSONAS}: expected an object with an integer version")
    if data["version"] != PERSONAS_VERSION:
        raise RenderError(f"{PERSONAS}: unsupported version {data['version']}")
    people = data.get("personas")
    if not isinstance(people, list) or not people:
        raise RenderError(f"{PERSONAS}: personas must be a non-empty list")
    out = {}
    for person in people:
        if not isinstance(person, dict) or not isinstance(person.get("key"), str):
            raise RenderError(f"{PERSONAS}: every persona needs a string key")
        key = person["key"]
        if key in out:
            raise RenderError(f"{PERSONAS}: duplicate persona key: {key}")
        fields = {}
        for field, value in person.items():
            if not isinstance(value, str):
                continue  # only string fields are substitutable
            if any(unicodedata.category(ch) == "Cc" for ch in value):
                raise RenderError(f"{PERSONAS}: control character in {key}.{field}")
            fields[field] = value
        out[key] = fields
    return out


def load_manifest(root, personas):
    data = load_json(root, MANIFEST, MANIFEST)
    if not isinstance(data, dict):
        raise RenderError(f"{MANIFEST}: expected an object")
    unknown = sorted(set(data) - MANIFEST_KEYS)
    missing = sorted(MANIFEST_KEYS - set(data))
    if unknown or missing:
        raise RenderError(f"{MANIFEST}: unknown key(s) {unknown} / missing key(s) {missing}")
    if not _is_int(data["version"]) or data["version"] != MANIFEST_VERSION:
        raise RenderError(f"{MANIFEST}: unsupported version {data['version']!r}")
    docs = data["documents"]
    if not isinstance(docs, list) or not docs:
        raise RenderError(f"{MANIFEST}: documents must be a non-empty list")
    known_fields = set().union(*personas.values())
    entries, sources, outputs = [], set(), set()
    for index, entry in enumerate(docs):
        where = f"{MANIFEST}: documents[{index}]"
        if not isinstance(entry, dict):
            raise RenderError(f"{where}: expected an object")
        keys = set(entry)
        if keys - ENTRY_REQUIRED - ENTRY_OPTIONAL or ENTRY_REQUIRED - keys:
            raise RenderError(f"{where}: keys must be source, output and optional "
                              f"forbidden_fields; got {sorted(keys)}")
        source = check_relpath(entry["source"], f"{where}.source")
        output = check_relpath(entry["output"], f"{where}.output")
        if not source.startswith(TEMPLATE_DIR) or not source.endswith(SOURCE_SUFFIX):
            raise RenderError(f"{where}.source: must be {TEMPLATE_DIR}*{SOURCE_SUFFIX}: {source}")
        if not output.endswith(OUTPUT_SUFFIX) or output.startswith((TEMPLATE_DIR, "synthetic/")):
            raise RenderError(f"{where}.output: must be a {OUTPUT_SUFFIX} file outside "
                              f"{TEMPLATE_DIR} and synthetic/: {output}")
        if source in sources:
            raise RenderError(f"{where}: duplicate source: {source}")
        if output in outputs:
            raise RenderError(f"{where}: duplicate output: {output}")
        sources.add(source)
        outputs.add(output)
        forbidden = entry.get("forbidden_fields", [])
        if (not isinstance(forbidden, list) or len(set(map(str, forbidden))) != len(forbidden)
                or not all(isinstance(f, str) for f in forbidden)):
            raise RenderError(f"{where}.forbidden_fields: must be a list of unique strings")
        for field in forbidden:
            if field not in known_fields:
                raise RenderError(f"{where}.forbidden_fields: unknown field: {field}")
        entries.append({"source": source, "output": output, "forbidden": tuple(forbidden)})
    # Sources live only under TEMPLATE_DIR with SOURCE_SUFFIX and outputs only
    # outside it with OUTPUT_SUFFIX, so a source and an output never overlap.
    return entries


def _position(text, offset):
    line = text.count("\n", 0, offset) + 1
    return line, offset - (text.rfind("\n", 0, offset) + 1) + 1


def normalize(text):
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return text.rstrip("\n") + "\n"


def substitute(template, personas, forbidden=(), what="template"):
    """One pass over the template; inserted values are never re-scanned."""
    out, last = [], 0
    for match in SCAN.finditer(template):
        out.append(template[last:match.start()])
        last = match.end()
        token = match.group(0)
        if token == "{{":
            out.append("{")
        elif token == "}}":
            out.append("}")
        elif match.group(1) is None:
            line, col = _position(template, match.start())
            raise RenderError(f"{what}:{line}:{col}: unescaped or malformed brace "
                              "(write {{ or }} for a literal brace)")
        else:
            key, field = match.group(1), match.group(2)
            line, col = _position(template, match.start())
            if key not in personas:
                raise RenderError(f"{what}:{line}:{col}: unknown persona key: {key}")
            if field not in personas[key]:
                raise RenderError(f"{what}:{line}:{col}: unknown string field: {key}.{field}")
            if field in forbidden:
                raise RenderError(f"{what}:{line}:{col}: field forbidden in this output: "
                                  f"{key}.{field}")
            out.append(personas[key][field])
    out.append(template[last:])
    return "".join(out)


def render(root, entry, personas):
    """The exact bytes an output must hold."""
    source = entry["source"]
    template = normalize(decode_text(read_regular(root, source, source), source))
    body = substitute(template, personas, entry["forbidden"], source)
    for field in entry["forbidden"]:
        for key, fields in sorted(personas.items()):
            if field in fields and fields[field] and fields[field] in body:
                raise RenderError(f"{source}: forbidden field {key}.{field} appears "
                                  f"literally in {entry['output']}")
    text = normalize(NOTICE.format(source=source) + body)
    return text.encode("utf-8")


def committed_bytes(root, rel):
    """Current bytes of an output, or None when it is absent."""
    full = contained(root, rel, rel)
    try:
        mode = os.lstat(full).st_mode
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(mode):
        raise RenderError(f"{rel}: output is not a regular file")
    return full.read_bytes()


def in_ci(environ):
    return environ.get("GITHUB_ACTIONS") == "true" or environ.get("CI") == "true"


def write_output(root, rel, data):
    full = contained(root, rel, rel)
    parent = full.parent
    if not parent.is_dir():
        raise RenderError(f"{rel}: output directory does not exist")
    fd, tmp = tempfile.mkstemp(dir=parent, prefix=".render-", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.replace(tmp, full)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def run(root, write=False, environ=None, out=sys.stdout, err=sys.stderr):
    environ = os.environ if environ is None else environ
    if write and in_ci(environ):
        print("persona render error: --write is refused in CI; render locally and "
              "commit the outputs", file=err)
        return 2
    try:
        root = Path(root).resolve(strict=True)
        personas = load_personas(root)
        entries = load_manifest(root, personas)
        rendered = [(entry, render(root, entry, personas)) for entry in entries]
        drift = sorted(entry["output"] for entry, data in rendered
                       if committed_bytes(root, entry["output"]) != data)
        if write:
            for entry, data in rendered:
                if entry["output"] in drift:
                    write_output(root, entry["output"], data)
                    print(f"persona render wrote: {entry['output']}", file=out)
            print(f"persona docs OK: {len(rendered)} document(s)", file=out)
            return 0
    except (RenderError, OSError) as exc:
        print(f"persona render error: {exc}", file=err)
        return 2
    for rel in drift:
        source = next(e["source"] for e, _ in rendered if e["output"] == rel)
        print(f"persona render drift: {rel} differs from {source} "
              "(edit the template, then run with --write)", file=err)
    if drift:
        return 1
    print(f"persona docs OK: {len(rendered)} document(s)", file=out)
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".", help="repository root (default: .)")
    parser.add_argument("--write", action="store_true",
                        help="update drifted outputs (local only; refused in CI)")
    args = parser.parse_args(argv)
    return run(args.root, write=args.write)


if __name__ == "__main__":
    sys.exit(main())
